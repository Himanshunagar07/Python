'''
=, +=, -=, *=, /=, %=, **=, //= are assignment operators.
'''

# Example:
x = 10
x += 5  # Equivalent to x = x + 5
print(int(x))  # Output: 15
x -= 3  # Equivalent to x = x - 3
print(int(x))  # Output: 12
x *= 2  # Equivalent to x = x * 2
print(int(x))  # Output: 24
x /= 2  # Equivalent to x = x / 2
print(int(x))  # Output: 12.0
x %= 5  # Equivalent to x = x % 5
print(int(x))  # Output: 2.0
x **= 2  # Equivalent to x = x ** 2
print(int(x))  # Output: 4.0
x //= 2  # Equivalent to x = x // 2
print(int(x))  # Output: 2.0)